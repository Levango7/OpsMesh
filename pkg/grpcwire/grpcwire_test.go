// grpcwire_test.go：本包是 6 个服务共用的 gRPC 线路守卫，自带自测以防"判据自己失明"。
//
// 覆盖：
//   - firstLine 纯函数
//   - generatedFileProblem：合格生成物不报、手写/错版本/缺失必须报（负向是本包的重点——
//     一个只会报红的门禁若自身无法被判红，就等于没有门禁）
//   - AssertGeneratedFilesLookGenerated 正向不误报
//   - ServeBufconn：手搭 unary 服务 + emptypb 做一次真实拨号/编解码/收尾冒烟
package grpcwire

import (
	"context"
	"os"
	"path/filepath"
	"testing"
	"time"

	"google.golang.org/grpc"
	"google.golang.org/protobuf/types/known/emptypb"
)

func TestFirstLine(t *testing.T) {
	cases := []struct{ in, want string }{
		{"abc", "abc"},
		{"abc\ndef", "abc"},
		{"\nx", ""},
		{"", ""},
	}
	for _, c := range cases {
		if got := firstLine(c.in); got != c.want {
			t.Errorf("firstLine(%q)=%q want %q", c.in, got, c.want)
		}
	}
}

func TestGeneratedFileProblem(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
		return p
	}

	msgOK := write("a.pb.go", "// Code generated by protoc-gen-go v1.36.12. DO NOT EDIT.\npackage x\n")
	grpcOK := write("a_grpc.pb.go", "// Code generated by protoc-gen-go-grpc v1.6.2. DO NOT EDIT.\npackage x\n")
	handwritten := write("hand.pb.go", "// 手写类型（非 protoc 产物）\npackage x\n")
	wrongVer := write("old.pb.go", "// Code generated by protoc-gen-go v1.34.0. DO NOT EDIT.\npackage x\n")
	missing := filepath.Join(dir, "nope.pb.go")

	cases := []struct {
		name    string
		path    string
		wantBad bool
	}{
		{"消息生成物合格", msgOK, false},
		{"grpc 生成物合格", grpcOK, false},
		{"手写文件必须判红", handwritten, true},
		{"工具链版本不符必须判红", wrongVer, true},
		{"文件缺失必须判红", missing, true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := generatedFileProblem(c.path)
			if c.wantBad && got == "" {
				t.Fatalf("期望判红却返回合格：%s", c.path)
			}
			if !c.wantBad && got != "" {
				t.Fatalf("期望合格却报问题：%q", got)
			}
		})
	}
}

// 正向：合格生成物不应让 AssertGeneratedFilesLookGenerated 报错；一旦误报，本测试即失败。
func TestAssertGeneratedFilesLookGenerated_Positive(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "ok_grpc.pb.go")
	if err := os.WriteFile(p, []byte("// Code generated by protoc-gen-go-grpc v1.6.2. DO NOT EDIT.\npackage x\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	AssertGeneratedFilesLookGenerated(t, p)
}

// ServeBufconn 冒烟：用手搭的 unary 服务 + emptypb 走一次真实 请求→编解码→响应→清理，
// 覆盖拨号（passthrough）与 server 收尾链路，不依赖任何服务的生成物。
func TestServeBufconn_UnaryRoundTrip(t *testing.T) {
	conn, cleanup := ServeBufconn(t, func(srv *grpc.Server) {
		srv.RegisterService(&grpc.ServiceDesc{
			ServiceName: "smoke.Grpcwire",
			HandlerType: (*any)(nil),
			Methods: []grpc.MethodDesc{{
				MethodName: "Ping",
				Handler: func(_ any, _ context.Context, dec func(any) error, _ grpc.UnaryServerInterceptor) (any, error) {
					in := &emptypb.Empty{}
					if err := dec(in); err != nil {
						return nil, err
					}
					return &emptypb.Empty{}, nil
				},
			}},
		}, struct{}{})
	})
	defer cleanup()

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := conn.Invoke(ctx, "/smoke.Grpcwire/Ping", &emptypb.Empty{}, &emptypb.Empty{}); err != nil {
		t.Fatalf("bufconn 往返失败：%v", err)
	}
}
