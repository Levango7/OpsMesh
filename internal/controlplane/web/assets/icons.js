// ---------- icon(name, size, cls) ----------
// 返回内联 SVG HTML 字符串。
//   name: 图标名（见 ICONS）
//   size: 像素尺寸，默认 18
//   cls:  额外 class（可选）
export function icon(name, size, cls) {
  const s = size || 18;
  const paths = ICONS[name];
  if (!paths) return ''; // 未知图标返回空串，避免报错
  const c = cls ? ' class="icon ' + cls + '"' : ' class="icon"';
  return '<svg' + c + ' width="' + s + '" height="' + s + '" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">' + paths + '</svg>';
}

// ---------- iconEl(name, size, cls) ----------
// 返回 DOM 元素（便于 appendChild）。
export function iconEl(name, size, cls) {
  const wrapper = document.createElement('span');
  wrapper.innerHTML = icon(name, size, cls);
  return wrapper.firstChild;
}

