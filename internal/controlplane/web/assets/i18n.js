const PACKS = { zh: ZH, en: EN };

// ---------- 当前语言 ----------
let currentLang = 'zh';

// ---------- t(key, params) ----------
// 翻译键值，支持 {placeholder} 插值。
//   key:   翻译键
//   params: 插值参数（可选），如 t('common.page', {cur: 2, total: 5})
export function t(key, params) {
  const pack = PACKS[currentLang] || ZH;
  let s = pack[key];
  if (s == null) {
    // 回退到中文
    s = ZH[key];
    if (s == null) return key; // 未知键返回键名本身（便于排查）
  }
  if (params) {
    Object.keys(params).forEach(function (k) {
      s = s.split('{' + k + '}').join(String(params[k]));
    });
  }
  return s;
}

// ---------- getLang() ----------
export function getLang() {
  return currentLang;
}

// ---------- setLang(lang) ----------
export function setLang(lang) {
  if (LANGS.indexOf(lang) < 0) lang = 'zh';
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.setAttribute('lang', lang === 'zh' ? 'zh-CN' : 'en');
  updateToggleButton(lang);
  // 触发语言变更事件，便于各模块重渲染
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
}

// ---------- toggleLang() ----------
export function toggleLang() {
  setLang(currentLang === 'zh' ? 'en' : 'zh');
}

// ---------- 更新切换按钮图标 ----------
function updateToggleButton(lang) {
  const btn = document.getElementById('langToggleBtn');
  if (!btn) return;
  // zh 时显示 EN（点击切到 en），en 时显示中（点击切到 zh）
  const iconName = lang === 'zh' ? 'lang-en' : 'lang-cn';
  btn.innerHTML = icon(iconName, 18);
  btn.setAttribute('title', lang === 'zh' ? 'Switch to English' : '切换到中文');
  btn.setAttribute('aria-label', lang === 'zh' ? 'Switch to English' : '切换到中文');
}

// ---------- initI18n() ----------
export function initI18n() {
  let lang = localStorage.getItem(STORAGE_KEY);
  if (LANGS.indexOf(lang) < 0) lang = 'zh';
  setLang(lang);
  // 绑定切换按钮
  const btn = document.getElementById('langToggleBtn');
  if (btn) {
    btn.addEventListener('click', toggleLang);
  }
}